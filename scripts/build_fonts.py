#!/usr/bin/env python3
"""Self-host the site fonts (no Google Fonts / CDN at runtime; works from mainland China).

Pulls the Fontsource woff2 slices from jsDelivr, keeps only the slices whose unicode-range
contains a character actually used in index.html, and writes assets/fonts/*.woff2 plus
assets/fonts.css.  Re-run after you add new Chinese text:   python3 scripts/build_fonts.py

Stdlib only.  Fonts are SIL OFL 1.1 (Newsreader, Inter, JetBrains Mono, Noto Serif/Sans SC).
"""
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "fonts"
CDN = "https://cdn.jsdelivr.net/npm/"

# (package, css file) — order = order in fonts.css
FAMILIES = [
    ("@fontsource-variable/newsreader", "index.css"),         # Latin display serif, roman
    ("@fontsource-variable/newsreader", "wght-italic.css"),   # ... italic (quote)
    ("@fontsource-variable/inter", "index.css"),              # Latin UI / body sans
    ("@fontsource/jetbrains-mono", "400.css"),                # mono labels
    ("@fontsource/jetbrains-mono", "500.css"),
    ("@fontsource-variable/noto-serif-sc", "index.css"),      # CJK serif (headings, quote)
    ("@fontsource-variable/noto-sans-sc", "index.css"),       # CJK sans (body)
]
# Always keep these even if not (yet) in index.html: basic CJK punctuation + digits.
EXTRA = "，。、；：？！“”‘’（）《》—…·→↗↓×"


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def parse_ranges(spec: str):
    out = []
    for part in spec.split(","):
        part = part.strip().upper().removeprefix("U+")
        if "-" in part:
            a, b = part.split("-")
            out.append((int(a, 16), int(b, 16)))
        elif part:
            out.append((int(part, 16), int(part, 16)))
    return out


def main() -> int:
    text = (ROOT / "index.html").read_text(encoding="utf-8") + EXTRA
    used = {ord(c) for c in text if ord(c) > 0x20}
    OUT.mkdir(parents=True, exist_ok=True)
    css_chunks, kept_files = [], set()
    total = 0
    for pkg, css_name in FAMILIES:
        base = f"{CDN}{pkg}/"
        css = fetch(base + css_name).decode("utf-8")
        for m in re.finditer(r"/\*.*?\*/\s*(@font-face\s*\{.*?\})", css, re.S):
            block = m.group(1)
            rng = re.search(r"unicode-range:\s*([^;]+);", block)
            ranges = parse_ranges(rng.group(1)) if rng else [(0, 0x10FFFF)]
            if not any(lo <= cp <= hi for cp in used for lo, hi in ranges):
                continue
            url = re.search(r"url\(\./files/([^)]+\.woff2)\)", block)
            if not url:
                continue
            name = url.group(1)
            dest = OUT / name
            if not dest.exists():
                dest.write_bytes(fetch(base + "files/" + name))
            kept_files.add(name)
            total += dest.stat().st_size
            block = block.replace(f"url(./files/{name})", f"url(fonts/{name})")
            css_chunks.append(block)
    # drop stale slices from previous runs
    for f in OUT.glob("*.woff2"):
        if f.name not in kept_files:
            f.unlink()
    (ROOT / "assets" / "fonts.css").write_text(
        "/* generated by scripts/build_fonts.py — do not edit */\n" + "\n".join(css_chunks) + "\n",
        encoding="utf-8",
    )
    print(f"{len(kept_files)} font files, {total/1024:.0f} KiB -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
